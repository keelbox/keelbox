// Primer writes one AGENTS.md describing the box and links it into every
// agent's user-scope instructions: Claude Code imports it from
// ~/.claude/CLAUDE.md, Codex reads it as ~/.codex/AGENTS.md.
type Primer struct{}

func (Primer) Name() string                  { return "primer" }
func (Primer) Enabled(c *config.Config) bool { return c.PrimerEnabled() }

// PrimerPath is root-owned and the agent has neither sudo nor the docker
// group, so the agent reads it but cannot rewrite it by ordinary means.
const PrimerPath = "/etc/keelbox/AGENTS.md"


// RenderPrimer renders AGENTS.md for a config.
func RenderPrimer(e *engine.Env) string {
	c := e.Cfg
	var size, small string
	if h := snap.ReadHost(context.Background(), e.X); h != nil && h.CPUs > 0 && h.Memory > 0 {
		size = fmt.Sprintf("%d CPU(s) and %s memory", h.CPUs, agentlimits.Size(h.Memory))
		if why := SmallHost(h.CPUs, h.Memory); why != "" {
			small = strings.SplitN(why, ", ", 2)[1]
		}
	}
	// The ceiling in the units the agent sees in free and top; a share of
	// RAM that could not be read stays a share.
	var memMax, memHigh string
	if l, on := limitsMemory(c); on {
		switch ram := readMemInfo(e).RAM; {
		case l.MemoryBytes > 0:
			memMax, memHigh = agentlimits.Size(l.MemoryBytes), agentlimits.Size(l.MemoryHighBytes())
		case ram > 0:
			memMax, memHigh = agentlimits.Size(ram/100*int64(l.MemoryPercent)), agentlimits.Size(ram/100*int64(l.MemoryHighPercent()))
		default:
			memMax, memHigh = fmt.Sprintf("%d%%", l.MemoryPercent), fmt.Sprintf("%d%%", l.MemoryHighPercent())
		}
		if !l.SlowDown {
			memHigh = ""
		}
	}
	var b bytes.Buffer
	_ = primerTmpl.Execute(&b, map[string]any{
		"MemoryMax": memMax, "MemoryHigh": memHigh,
		"Box": c.Box, "OS": e.Facts.OSVersion, "Agent": c.Users.Agent.Name, "Sudo": c.AgentSudo(), "Permissions": c.AgentPermissions(),
		"Tailscale": c.Tailscale(), "Allow": config.AllowSummary(c.Host.Firewall.Allow), "Node": c.Node(), "NodeVersion": e.M.Node, "PnpmVersion": e.M.Pnpm,
		"Docker": c.Docker(), "Tmux": c.Tmux(), "Recovery": c.TmuxRecovery(),
		"Previews": c.PreviewsEnabled(), "Backup": c.BackupEnabled(), "AutoReboot": c.RebootsItself(), "Weekly": c.Host.AutoReboot == config.AutoRebootWeekly,
		"Hooks": len(c.Notify.Channels) > 0, "AgentText": c.NotifyAgentText(),
		"Codex": slices.Contains(c.Agents, config.AgentCodex), "AgentCLIs": agentCLIList(c.Agents), "Reports": c.ReportsEnabled(), "Size": size, "Small": small,
		"Notes":    strings.TrimSpace(c.Primer.Notes),
		"Projects": c.ProjectsDir(), "GitIdentity": gitIdentity(c),
	})
	return b.String()
}

func (p Primer) Steps(e *engine.Env) []engine.Step {
	u := e.AgentUser()
	return []engine.Step{
		engine.DirStep("primer-dir", "/etc/keelbox", 0o755, "root", "root"),
		engine.FileStep("primer", engine.File{Path: PrimerPath, Content: []byte(RenderPrimer(e)), Mode: 0o644}),
		engine.DirStep("claude-dir", u.Home+"/.claude", 0, u.Name, u.Name),
		engine.LineStep("claude-import", u.Home+"/.claude/CLAUDE.md", "@"+PrimerPath, 0o644, u.Name),
		engine.DirStep("codex-dir", u.Home+"/.codex", 0, u.Name, u.Name),
		codexLinkStep(u),
	}
}

// codexLinkStep links ~/.codex/AGENTS.md to the primer, but never replaces a
// regular file the user wrote.
func codexLinkStep(u system.User) engine.Step {
	link := u.Home + "/.codex/AGENTS.md"
	return engine.Step{
		Name: "codex-agents-md",
		User: u.Name,
		Check: func(ctx context.Context, e *engine.Env) (engine.Status, error) {
			st, err := e.FS(u.Name).Stat(link)
			switch {
			case err != nil:
				return engine.Status{}, err
			case !st.Exists:
				return engine.Pending("link %s to the primer", link), nil
			case st.IsSymlink && st.LinkTarget == PrimerPath:
				return engine.Converged(), nil
			case st.IsSymlink:
				return engine.Pending("repoint %s to the primer", link), nil
			}
			return engine.Converged(), nil // the user's own file: leave it
		},
		Apply: func(ctx context.Context, e *engine.Env) error { return e.FS(u.Name).Symlink(PrimerPath, link) },
	}
}

func (Primer) Verify(ctx context.Context, e *engine.Env) []engine.Finding {
	u := e.AgentUser()
	if st, _ := e.FS(u.Name).Stat(u.Home + "/.codex/AGENTS.md"); st.Exists && !st.IsSymlink {
		return []engine.Finding{warn("primer", "codex", "~/.codex/AGENTS.md is the user's own file; add the primer to it by hand")}
	}
	if !system.Succeeds(ctx, e.X, system.As(u.Name, "test", "-r", PrimerPath)) {
		return []engine.Finding{fail("primer", "readable", PrimerPath+" not readable by "+u.Name)}
	}
	return []engine.Finding{ok("primer", "readable", PrimerPath+" linked for Claude Code and Codex")}
}

func gitIdentity(c *config.Config) bool {
	_, _, ok := c.AgentGit()
	return ok
}

// agentCLIList names the box's agent CLIs for the primer, by their
// commands: "claude and codex".
func agentCLIList(agents []string) string {
	var bins []string
	for _, id := range agents {
		if spec, ok := agentSpecs[id]; ok {
			bins = append(bins, "`"+spec.bin+"`")
		}
	}
	return strings.Join(bins, " and ")
}

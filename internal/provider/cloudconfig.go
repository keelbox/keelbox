package provider

import (
	"fmt"
	"strings"

	"go.yaml.in/yaml/v3"
)

// CloudConfig is the cloud-config a user pastes into a provider's "Cloud
// config" or "User data" field when creating an Ubuntu server themselves
// (docs/adr/0028-cloud-config-snippet.md). It creates the admin account with
// the user's SSH keys and passwordless sudo (it has no password), turns off
// SSH passwords and root login, and, when hostKey is set, installs a host
// key keelbox generated so the first connection is checked against it.
// It holds no credentials. The host key is single-use: the provider's
// metadata service may serve user data to anything on the server, so
// keelbox replaces it with keys made on the server at its first
// connection (SSH.RotateHostKeys).
func CloudConfig(box, admin string, keys []string, hostKey *HostKeyPair) (string, error) {
	head := "#cloud-config\n# keelbox box " + box + ": paste into the provider's \"Cloud config\" or \"User data\" field\n" +
		"# when creating an Ubuntu 24.04 or newer server. No credentials: it creates the account\n" +
		"# " + admin + " with your SSH key; keelbox and its config arrive over SSH afterwards.\n"
	if hostKey != nil {
		head += "# The host key below is single-use: keelbox checks the server against it at the first\n" +
			"# connection, then replaces it with keys made on the server.\n"
	}
	body, err := adminCloudConfig(box, admin, keys, hostKey)
	if err != nil {
		return "", err
	}
	return head + body, nil
}

// AdminUserData is the cloud-init document for a server keelbox creates
// on a cloud whose image would otherwise be reached as root with a key
// stored in the cloud account: it creates the admin account with the
// user's SSH keys instead, turns off SSH passwords and root login, and
// installs the single-use host key generated on the laptop (see
// UserData). The first apply then runs as the admin, and no key is added
// to the account.
func AdminUserData(box, hostname, admin string, keys []string, hk HostKeyPair) (string, error) {
	body, err := adminCloudConfig(hostname, admin, keys, &hk)
	if err != nil {
		return "", err
	}
	return "#cloud-config\n# keelbox box " + box + ". keelbox and its config arrive over SSH after first boot.\n" + body, nil
}

// adminCloudConfig is the body both documents share.
func adminCloudConfig(hostname, admin string, keys []string, hostKey *HostKeyPair) (string, error) {
	type user struct {
		Name              string   `yaml:"name"`
		PrimaryGroup      string   `yaml:"primary_group"`
		Shell             string   `yaml:"shell"`
		Sudo              string   `yaml:"sudo"`
		LockPasswd        bool     `yaml:"lock_passwd"`
		SSHAuthorizedKeys []string `yaml:"ssh_authorized_keys"`
	}
	doc := struct {
		Hostname      string            `yaml:"hostname"`
		Users         []user            `yaml:"users"`
		SSHPwauth     bool              `yaml:"ssh_pwauth"`
		DisableRoot   bool              `yaml:"disable_root"`
		SSHDeleteKeys bool              `yaml:"ssh_deletekeys,omitempty"`
		SSHKeys       map[string]string `yaml:"ssh_keys,omitempty"`
	}{
		Hostname: hostname,
		// Ubuntu images have an admin group (an old sudo group, now empty),
		// and useradd refuses to create a user of that name without -g.
		// cloud-init passes --gid for primary_group, creating it if missing.
		Users: []user{{Name: admin, PrimaryGroup: admin, Shell: "/bin/bash", Sudo: "ALL=(ALL) NOPASSWD:ALL", LockPasswd: true,
			SSHAuthorizedKeys: keys}},
		DisableRoot: true,
	}
	if len(keys) == 0 {
		return "", fmt.Errorf("no SSH public key for %s", admin)
	}
	if hostKey != nil {
		// With ssh_keys set, cloud-init writes these and generates none.
		doc.SSHDeleteKeys = true
		doc.SSHKeys = map[string]string{"ed25519_private": hostKey.Private, "ed25519_public": strings.TrimSpace(hostKey.Public)}
	}
	body, err := yaml.Marshal(doc)
	if err != nil {
		return "", fmt.Errorf("render cloud-config: %w", err)
	}
	return string(body), nil
}

// HostKeyPair is an OpenSSH host key generated by GenerateHostKey.
type HostKeyPair struct {
	Private, Public string
}
